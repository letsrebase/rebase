"""What the English lint does not look at, and why. Small on purpose: every entry is a
sentence of justification, and a new one is a decision to review, not a way to make a red
run green.

Three kinds of entry:

* `SKIP_PATHS`: files that are never read (generated, dated records, history).
* `LEGACY_REVISIONS`: Alembic revisions that existed before the rename. They keep the
  words of the schema they migrated; the revisions written after the rename are linted.
* `ALLOW`: a path glob plus the Italian words that stay legal in the files it matches.
  `words=None` allows every word (an Italian module on purpose); a `kinds` filter keeps
  the entry from allowing more than it must.

String literals are never checked, so the Italian a person reads (UI copy, messages,
OpenAPI and MCP descriptions as strings, template content, template variables, custom
field keys, the SQL a migration runs) needs no entry here.

Globs: `*` is one path segment's characters, `**` any number of segments.
"""

