"""Whether a card still matches what would be written now, and what it would cost to write
it again (REB-891, REB-804, REB-892: split out of `cards.py`).

`CardStaleness` is the part of `CardWriter` that reads this. It compares the CV by the stored
digest (`freelancers.cv_sha256`, generated by the database: no CV is hashed here) and the
other inputs by their hashes (`card_provenance.hash_inputs`). The list of stale cards reads
the people's positions, sources and hub facts a page at a time with one query each
(`input_hashes_many`), never one set of queries per card, and stops at `limit`.
"""

from collections.abc import Sequence
from decimal import Decimal
from typing import Literal
from uuid import UUID

from sqlalchemy import func, select

from rebase_core.card_base import CardBase
from rebase_core.card_prompt import PROMPT_VERSION
from rebase_core.card_provenance import hash_inputs, stale_reason
from rebase_core.card_types import StaleCard
from rebase_core.hub_facts import hub_facts_many
from rebase_core.models import AiUsage, Freelancer, FreelancerCard, User

# How many of the latest `card` calls the stale list's estimate averages.
ESTIMATE_CALLS = 50

# How many cards of the stale list are read at a time: the cards, their people's positions, their
# sources and their hub facts, each page in a constant number of queries.
STALE_PAGE = 200


class CardStaleness(CardBase):
    """Why a card is stale, the list of those that wait for an admin's start, and the cost
    of writing them again."""

    def input_hashes(self, freelancer_id: UUID) -> dict[str, str]:
        """The hash of every input a card of this person is written from, as stored now:
        `wizard` (the position), `hub` (the hub's facts, when there are any) and each
        readable source (`github`, `link:<n>`). What `source_hashes` keeps at write time."""
        self._freelancer(freelancer_id)
        return self.input_hashes_many([freelancer_id])[freelancer_id]

    def input_hashes_many(self, freelancer_ids: Sequence[UUID]) -> dict[UUID, dict[str, str]]:
        """`input_hashes` for several people in four queries in all: the same hashes for each,
        read by `IN (...)`. A person who does not exist is not in the answer."""
        wanted = list(dict.fromkeys(freelancer_ids))
        if not wanted:
            return {}
        positions = {
            person: position
            for person, position in self.session.execute(
                select(Freelancer.id, Freelancer.posizione).where(Freelancer.id.in_(wanted))
            )
        }
        sources = self.source_service().current_many(list(positions))
        facts = hub_facts_many(self.session, list(positions))
        return {
            person: hash_inputs(positions[person], sources[person], facts[person])
            for person in positions
        }

    def stale_of(self, freelancer_id: UUID) -> Literal["cv", "source", "prompt"] | None:
        """Why the person's card is no longer what the current inputs would write, if it
        is not (`stale_reason`)."""
        cv_hash = self.cv_digest(freelancer_id)
        stored = self.session.get(FreelancerCard, freelancer_id, populate_existing=True)
        if stored is None:
            return None
        behind = (stored.prompt_version or 1) != PROMPT_VERSION
        hashes = {} if behind else self.input_hashes(freelancer_id)
        return stale_reason(stored, cv_hash, hashes)

    def stale_cards(self, limit: int | None = None) -> list[StaleCard]:
        """The cards that wait for an admin's start, the oldest first, those whose last try
        failed on their own account last: written by another prompt version, or from inputs
        (the hub's facts, the position, a source) that are not the ones stored now. A card
        stale by its CV is not here: the hourly loop writes it again by itself. Only a card
        that exists and whose person is live and not turned down; the CV is compared by the
        stored digest, as in `refresh_stale`. The inputs are hashed only for a card of the
        current version: one of another version is stale whatever they are.

        `limit` stops the reading at that many: an admin's start works through the first
        `limit` (`regenerate_stale`) and has no use for the rest, and the list is read a page
        at a time (`STALE_PAGE`) in a fixed order, so the cards a start does not reach are
        the next one's, in the same order. Without it, every stale card."""
        waiting: list[StaleCard] = []
        offset = 0
        while limit is None or len(waiting) < limit:
            page = self.session.execute(
                select(FreelancerCard, Freelancer.cv_sha256, User.nome, User.cognome)
                .join(Freelancer, Freelancer.id == FreelancerCard.freelancer_id)
                .join(User, User.id == Freelancer.user_id)
                .where(
                    Freelancer.deleted_at.is_(None),
                    Freelancer.stato != "scartato",
                    Freelancer.cv_sha256.is_not(None),
                    FreelancerCard.card.is_not(None),
                )
                # A card whose last try failed on its own account goes last: a person whose
                # card keeps failing the guards would otherwise be first at every start and
                # pay two calls each time while the rest never get a turn.
                .order_by(
                    FreelancerCard.error_cv_sha256.is_not(None),
                    FreelancerCard.generated_at,
                    FreelancerCard.freelancer_id,
                )
                .limit(STALE_PAGE)
                .offset(offset)
            ).all()
            hashes = self.input_hashes_many(
                [
                    card.freelancer_id
                    for card, *_ in page
                    if (card.prompt_version or 1) == PROMPT_VERSION
                ]
            )
            for card, cv_hash, nome, cognome in page:
                reason = stale_reason(card, cv_hash, hashes.get(card.freelancer_id, {}))
                if reason == "prompt" or reason == "source":
                    waiting.append(
                        StaleCard(
                            card.freelancer_id,
                            f"{nome} {cognome}".strip(),
                            reason,
                            card.generated_at,
                        )
                    )
                    if limit is not None and len(waiting) >= limit:
                        return waiting
            if len(page) < STALE_PAGE:
                break
            offset += STALE_PAGE
        return waiting

    def estimate_cost(self, count: int) -> Decimal | None:
        """What `count` cards would cost to write: the average cost of the latest
        `ESTIMATE_CALLS` `card` calls recorded (a real one, not a «Prova», an evaluation or a
        Message Batch's, and one that had a price) times `count`. The latest, not all of
        them: a call is not
        marked with the prompt it ran, and the recent ones are the nearest to what the
        prompt carries now, sources included, where the average of every call since the
        first card would stay on the CV-only calls of version 1 (the most a prompt adds is
        `MAX_SOURCE_CHARS`). `None` while nothing is recorded: never zero, which would read
        as free."""
        latest = (
            select(AiUsage.cost_eur)
            .where(
                AiUsage.task == "card",
                AiUsage.purpose == "run",
                AiUsage.priced.is_(True),
                # A batch call is half a synchronous one: the estimate is of the call.
                AiUsage.batch.is_(False),
                # A spend hold is not a call: its row carries the estimate, not the cost.
                AiUsage.reserved_until.is_(None),
            )
            .order_by(AiUsage.at.desc())
            .limit(ESTIMATE_CALLS)
            .subquery()
        )
        average = self.session.scalar(select(func.avg(latest.c.cost_eur)))
        if average is None:
            return None
        return (Decimal(average) * count).quantize(Decimal("0.0001"))
